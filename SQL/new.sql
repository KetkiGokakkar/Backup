-- E1
SELECT T.TEAM_NAME , C.COACH_NAME ,C.EXPERIENCE_YEARS 
FROM TEAMS T JOIN COACHES C 
ON T.TEAM_ID =C.TEAM_ID
ORDER BY T.TEAM_NAME;

-- E2
SELECT T.TEAM_NAME ,P.PLAYER_NAME,P.POSITION,P.SALARY
FROM TEAMS T JOIN PLAYERS P 
ON T.TEAM_ID = P.TEAM_ID
WHERE P.POSITION ='FORWARD' 
ORDER BY TEAM_NAME , PLAYER_NAME;

-- E3
SELECT T.TEAM_NAME , COUNT(*) AS H_SAL_P_CNT ,SUM(P.SALARY )  AS HIGH_SAL_SUM
FROM TEAMS T JOIN PLAYERS P 
ON T.TEAM_ID = P.TEAM_ID 
WHERE P.SALARY>=65000
GROUP BY T.TEAM_NAME 
HAVING COUNT(*) >=2 
ORDER BY HIGH_SAL_SUM DESC ;

-- M1 
SELECT M.MATCH_ID , M.MATCH_DATE, T.TEAM_NAME , P.PLAYER_NAME  ,PS.POINTS ,
RANK() OVER(PARTITION BY M.MATCH_ID ORDER BY PS.POINTS DESC) AS POINTS_RANK
FROM TEAMS T JOIN PLAYERS P 
ON T.TEAM_ID = P.TEAM_ID 
JOIN PLAYER_STATS PS 
ON PS.PLAYER_ID = P.PLAYER_ID 
JOIN MATCHES M 
ON M.MATCH_ID = PS.MATCH_ID 
ORDER BY MATCH_ID , POINTS_RANK;

-- M2 
SELECT T.TEAM_NAME  , SUM(PS.POINTS ) AS TOT_POINTS 
, RANK() OVER  (ORDER BY SUM(PS.POINTS ) DESC)  AS RANK_
FROM TEAMS T JOIN PLAYERS P 
ON T.TEAM_ID = P.TEAM_ID 
JOIN PLAYER_STATS PS 
ON PS.PLAYER_ID = P.PLAYER_ID 
JOIN MATCHES M 
ON M.MATCH_ID = PS.MATCH_ID 
WHERE M.MATCH_STATUS = 'COMPLETED'
GROUP BY T.TEAM_NAME;

-- M3
SELECT TEAM_NAME ,MATCH_ID, MATCH_DATE, MATCH_POINTS ,
SUM(MATCH_POINTS  ) OVER 
	( PARTITION BY TEAM_NAME ORDER BY MATCH_ID ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW)
FROM (
SELECT T.TEAM_NAME ,M.MATCH_ID, M.MATCH_DATE  ,
SUM(PS.POINTS)  AS MATCH_POINTS
 
FROM TEAMS T JOIN PLAYERS P 
ON T.TEAM_ID = P.TEAM_ID 
JOIN PLAYER_STATS PS 
ON PS.PLAYER_ID = P.PLAYER_ID 
JOIN MATCHES M 
ON M.MATCH_ID = PS.MATCH_ID 
WHERE M.MATCH_STATUS = 'COMPLETED' 
GROUP BY T.TEAM_NAME ,M.MATCH_ID, M.MATCH_DATE 
ORDER BY TEAM_NAME , MATCH_DATE,MATCH_ID
  ) S 

