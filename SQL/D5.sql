-- TRIGGERS 

-- CREATE TRIGGER FOR AN UPDATE TRANSACTION IN EMP TABLE 

DELIMITER //
CREATE TRIGGER SAL_UPD_TRIG
AFTER UPDATE ON EMP FOR EACH ROW
BEGIN 
	IF OLD.SAL<> NEW.SAL THEN 
		INSERT INTO EMP_LOGS ( USER_ID , BEFORE_SAL , AFTER_sAL)
		VALUES(USER() ,OLD.SAL ,NEW.SAL);
	END IF ;
END //
DELIMITER ;

CREATE TABLE EMP_LOGS( USER_ID VARCHAR(20) , BEFORE_SAL INT , AFTER_SAL INT ) ;

UPDATE EMP SET SAL =SAL+3000 WHERE EMPNO =7499;
SELECT *FROM EMP ;
SELECT *FROM EMP_LOGS;

DELIMITER //
CREATE PROCEDURE EMP_UD_HANDLE(IN ACTION VARCHAR(10),IN EMP_ID INT )
BEGIN 
	INSERT INTO EMP_AUD(USER_ID  ,ACTION , EMPID, TIME_STAMP ) 
    VALUE ( USER() , ACTION  , EMP_ID , NOW());
END //
DELIMITER ;
DROP PROCEDURE EMP_UD_HANDLE;

CREATE TABLE EMP_AUD(USER_ID VARCHAR(20) , ACTION VARCHAR(10) , EMPID INT , TIME_STAMP DATETIME ) ;

DELIMITER //
CREATE TRIGGER ON_UPD
AFTER UPDATE ON EMP FOR EACH ROW 
BEGIN 
	CALL EMP_UD_HANDLE('UPDATE',NEW.EMPNO);
END //
DELIMITER ;

UPDATE EMP SET SAL = 62000.00 WHERE EMPNO = 7499;
 
-- AFTER DELETE Trigger:
DELIMITER //
CREATE TRIGGER after_emp_delete
AFTER DELETE ON EMP
FOR EACH ROW
BEGIN
    CALL EMP_UD_HANDLE('DELETE', OLD.id);
END //
DELIMITER ;