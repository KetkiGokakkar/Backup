SELECT 
	SUM(CASE WHEN FULLNAME IS NULL  OR TRIM(FULLNAME)=''THEN 1 ELSE 0 END) AS NullNames,
    SUM(CASE WHEN EMAIL IS NULL OR TRIM(EMAIL)='' THEN 1 ELSE 0 END) AS NullEmail,
    SUM(CASE WHEN PHONE IS NULL OR TRIM(PHONE)='' THEN 1 ELSE 0 END) AS NullPhone
FROM CUSTOMERS; 
-- DUPLICATE COUNT
SELECT FULLNAME , EMAIL , COUNT(*) AS DupCount
FROM CUSTOMERS 
GROUP BY FULLNAME,EMAIL
HAVING COUNT(*) >1;

-- INCONSISTENT COUNTRY VALUES 
SELECT  DISTINCT COUNTRY 
FROM CUSTOMERS ;


UPDATE CUSTOMERS 
