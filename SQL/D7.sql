-- W2 D2 
CREATE DATABASE W2D2COD;
USE W2D2COD;

CREATE TABLE DIM_CUSTOMER(
	CUSTOMER_KEY INT PRIMARY KEY ,    CUSTOMER_NAME VARCHAR(100),    REGION VARCHAR(50), 
    SEGMENT VARCHAR(50)
    );
CREATE TABLE DIM_PRODUCT (
	PRODUCT_KEY INT PRIMARY KEY ,	PRODUCT_NAME VARCHAR(100) ,    CATEGORY VARCHAR(50),
    SUB_CATEGORY VARCHAR(50)
    );
CREATE TABLE DIM_DATE(
	DATE_KEY INT PRIMARY KEY ,    FULL_DATE DATE,    DAY INT ,
    MONTH INT ,    QUARTER INT ,    YEAR INT 
    );
CREATE TABLE FACT_SALES(
	SALES_KEY INT PRIMARY KEY ,    DATE_KEY INT ,
    CUSTOMER_KEY INT ,    PRODUCT_KEY INT ,
    QUANTITY_SOLD INT ,    SALES_AMOUNT DECIMAL(10,2),
    FOREIGN KEY ( DATE_KEY )REFERENCES DIM_DATE(DATE_KEY),
    FOREIGN KEY ( CUSTOMER_KEY )REFERENCES DIM_CUSTOMER(CUSTOMER_KEY),
    FOREIGN KEY ( PRODUCT_KEY )REFERENCES DIM_PRODUCT(PRODUCT_KEY)
    );

