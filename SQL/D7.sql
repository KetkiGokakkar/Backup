SELECT * FROM FACT_SALES;

-- TOTAL SALES AMOUNT
SELECT SUM(SALES_AMOUNT) AS TOTAL_SALES
FROM FACT_SALES;

-- SALES BY CUSTOMER
SELECT C.CUSTOMER_NAME , SUM(F.SALES_AMOUNT) AS TOTAL_SALES
FROM FACT_SALES F JOIN DIM_CUSTOMER C 
ON F.CUSTOMER_KEY = C.CUSTOMER_KEY 
GROUP BY C.CUSTOMER_NAME;

-- SALES BY PRODUCT CATEGORY 
SELECT P.CATEGORY ,SUM(F.SALES_AMOUNT) AS TOTAL_SALES 
FROM FACT_sALES F JOIN DIM_PRODUCT P 
ON F.PRODUCT_KEY = P.PRODUCT_KEY 
GROUP BY P.CATEGORY ;

-- DAILY SALES TREND 
SELECT D.FULL_DATE , SUM(F.SALES_AMOUNT) AS DAILY_SALES 
FROM FACT_SALES F JOIN DIM_DATE D 
ON F.DATE_KEY = D.DATE_KEY 
GROUP BY D.FULL_DATE
 ORDER BY D.FULL_DATE;

