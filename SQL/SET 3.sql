FROM (
SELECT D.SPECIALIZATION , D.DOCTOR_NAME ,
SUM(B.BILL_AMOUNT) AS TOT_REV,
RANK()OVER(PARTITION BY D.SPECIALIZATION ORDER BY SUM(B.BILL_AMOUNT) DESC) AS RANK_N
FROM doctors d
JOIN appointments a 
    ON d.doctor_id = a.doctor_id
JOIN billing b 
    ON a.appointment_id = b.appointment_id
    GROUP BY D.SPECIALIZATION , D.DOCTOR_NAME) AS S
    WHERE RANK_N=1;
 
