SELECT 
    d.doctor_name AS `Doctor Name`,
    SUM(b.bill_amount) AS `Total Revenue Generated`
FROM doctors d
JOIN appointments a 
    ON d.doctor_id = a.doctor_id
JOIN billing b 
    ON a.appointment_id = b.appointment_id
GROUP BY d.doctor_id, d.doctor_name
HAVING SUM(b.bill_amount) > (
    SELECT AVG(doctor_revenue)
    FROM (
        SELECT 
            d2.doctor_id,
            SUM(b2.bill_amount) AS doctor_revenue
        FROM doctors d2
        JOIN appointments a2 
            ON d2.doctor_id = a2.doctor_id
        JOIN billing b2 
            ON a2.appointment_id = b2.appointment_id
        GROUP BY d2.doctor_id
    ) AS revenue_table
);


