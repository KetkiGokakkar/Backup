(SELECT P.PATIENT_NAME ,A.APPOINTMENT_DATE ,D.DOCTOR_NAME ,
ROW_NUMBER() OVER (PARTITION BY PATIENT_NAME ORDER BY A.APPOINTMENT_DATE DESC) AS RANK_N
FROM PATIENTS P JOIN APPOINTMENTS A 
ON P.PATIENT_ID = A.PATIENT_ID 
JOIN DOCTORS D 
ON A.DOCTOR_ID = D.DOCTOR_ID ) AS S
WHERE RANK_N =1;

