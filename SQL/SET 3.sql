FROM DOCTORS D JOIN APPOINTMENTS A ON D.DOCTOR_ID =  A.DOCTOR_ID 
JOIN TREATMENTS T ON A.APPOINTMENT_ID = T.APPOINTMENT_ID
JOIN (SELECT D.DOCTOR_NAME,MAX(T.TREATMENT_COST) AS MAX_T
FROM DOCTORS D JOIN APPOINTMENTS A ON D.DOCTOR_ID =  A.DOCTOR_ID 
JOIN TREATMENTS T ON A.APPOINTMENT_ID = T.APPOINTMENT_ID
GROUP BY D.DOCTOR_NAME) S ON D.DOCTOR_NAME=S.DOCTOR_NAME
WHERE T.TREATMENT_COST = MAX_T;

