    d.doctor_name AS `Doctor Name`,
SUM(b.bill_amount) AS TOT_REV,
    RANK() OVER (ORDER BY SUM(B.BILL_AMOUNT) DESC) AS RANK_
FROM doctors d
JOIN appointments a 
    ON d.doctor_id = a.doctor_id
JOIN billing b 
    ON a.appointment_id = b.appointment_id
GROUP BY d.doctor_id, d.doctor_name;

